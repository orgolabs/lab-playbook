#!/usr/bin/env bash
# Fetch real 3D structures from PubChem and embed them into js/structures.js.
# Usage (run from a lab's root):  ../lab-playbook/scripts/fetch-structures.sh name1:CID1 name2:CID2 ...
#   e.g.  fetch-structures.sh cyclopentadiene:7612 maleic_anhydride:7923 endo_adduct:12309
# Prefer DEFINED-stereochemistry CIDs — undefined-stereo records render the wrong 3D.
set -euo pipefail
[ "$#" -ge 1 ] || { echo "usage: fetch-structures.sh name:CID [name:CID ...]"; exit 1; }
mkdir -p data js
names=()
for pair in "$@"; do
  name="${pair%%:*}"; cid="${pair##*:}"
  echo "fetching $name (CID $cid)…"
  curl -fsSL "https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/cid/$cid/SDF?record_type=3d" -o "data/$name.sdf"
  atoms=$(sed -n '4p' "data/$name.sdf" | awk '{print $1}')
  echo "  -> data/$name.sdf ($atoms atoms)"
  names+=("$name")
done
# generate js/structures.js with safe JSON escaping
python3 -I - "${names[@]}" <<'PY'
import json, sys
names = sys.argv[1:]
with open("js/structures.js", "w") as out:
    out.write("// Real 3D geometries (MDL SDF) from PubChem PUG-REST. Generated by fetch-structures.sh.\n")
    out.write("// Embedded as strings so 3Dmol.js works from file:// and GitHub Pages without fetch/CORS.\n")
    out.write("window.STRUCTURES = {\n")
    for n in names:
        out.write(f"  {n}: {json.dumps(open('data/'+n+'.sdf').read())},\n")
    out.write("};\n")
print("wrote js/structures.js with:", ", ".join(names))
PY
